#!/usr/bin/env bash
# Regenerate THIRD_PARTY_NOTICES.md: every Go module linked into ./cmd/specs-index, with the license
# text copied from the module cache, plus the components the SQLite wrapper embeds.
# Needs the modules in the Go module cache (go mod download). A module without a license file
# is listed as UNKNOWN and reported on stderr; the script never guesses a license.
# Usage: scripts/gen-notices.sh [OUTPUT]   (default: THIRD_PARTY_NOTICES.md at the repository root)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$ROOT/THIRD_PARTY_NOTICES.md}"
cd "$ROOT"

hash() { if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -d' ' -f1; else shasum -a 256 | cut -d' ' -f1; fi; }

# SPDX-style id read from the text itself; UNKNOWN when it is not one of the known texts.
license_id() {
  local f="$1"
  if grep -q "Apache License" "$f" && grep -q "Version 2.0, January 2004" "$f"; then echo "Apache-2.0"
  elif grep -q "MIT No Attribution" "$f"; then echo "MIT-0"
  elif grep -q "Permission is hereby granted, free of charge" "$f"; then echo "MIT"
  elif grep -q "Redistribution and use in source and binary forms" "$f" && grep -q "Neither the name of" "$f"; then echo "BSD-3-Clause"
  else echo "UNKNOWN"; fi
}

mods="$(go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/... | sort -u)"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
unknown=()
: > "$tmp/index"
while read -r path version dir; do
  [ -n "$path" ] || continue
  found=0
  for f in "$dir"/LICENSE* "$dir"/COPYING* "$dir"/NOTICE* "$dir"/PATENTS; do
    [ -f "$f" ] || continue
    found=1
    name="$(basename "$f")"
    sum="$(hash < "$f")"
    case "$name" in
      NOTICE*|PATENTS) id="$name" ;;
      *) id="$(license_id "$f")" ;;
    esac
    [ "$id" = UNKNOWN ] && unknown+=("$path $version ($name)")
    printf '%s\t%s\t%s\t%s\t%s\n' "$sum" "$id" "$name" "$path $version" "$f" >> "$tmp/index"
  done
  if [ "$found" = 0 ]; then
    unknown+=("$path $version (no license file)")
    printf '%s\t%s\t%s\t%s\t%s\n' "none" "UNKNOWN" "-" "$path $version" "-" >> "$tmp/index"
  fi
done <<< "$mods"
sort -t "$(printf '\t')" -k1,1 -k4,4 -o "$tmp/index" "$tmp/index"

wasm_dir="$(go list -deps -f '{{with .Module}}{{if eq .Path "github.com/ncruces/go-sqlite3-wasm/v6"}}{{.Dir}}{{end}}{{end}}' ./cmd/... | sort -u | head -n1)"

{
  cat <<'EOF'
# Third-party notices

specs-index itself is MIT licensed (see LICENSE). The binaries link the Go modules listed below and, through the SQLite wrapper, the components in "Embedded in the SQLite wrapper". This file is generated by `scripts/gen-notices.sh` from the Go module cache; each license text below is copied from the module's own files. The Go standard library is not listed.

## Modules linked into the binary

EOF
  echo '| Module | Version | License file | License |'
  echo '| --- | --- | --- | --- |'
  while IFS="$(printf '\t')" read -r sum id name modver file; do
    case "$name" in NOTICE*|PATENTS) continue ;; esac
    mod="${modver% *}"; ver="${modver##* }"
    printf '| %s | %s | %s | %s |\n' "$mod" "$ver" "$name" "$id"
  done < <(sort -t "$(printf '\t')" -k4,4 "$tmp/index")
  cat <<'EOF'

The AWS SDK for Go v2 modules are Apache-2.0 and the SDK ships a NOTICE file (reproduced below). `golang.org/x/sys` is BSD-3-Clause and ships a PATENTS file (reproduced below).

## License texts

Modules that share a byte-identical text are grouped.
EOF
  prev=""
  while IFS="$(printf '\t')" read -r sum id name modver file; do
    if [ "$sum" != "$prev" ]; then
      prev="$sum"
      echo
      if [ "$id" = "$name" ]; then echo "### $name"; else echo "### $id ($name)"; fi
      echo
      echo "Applies to:"
      echo
      awk -F'\t' -v s="$sum" '$1==s {print "- " $4}' "$tmp/index"
      echo
      if [ "$file" = "-" ]; then
        echo "UNKNOWN: no license file was found in the module."
      else
        echo '```text'
        cat "$file"
        # make sure the closing fence starts on its own line
        [ -z "$(tail -c1 "$file")" ] || echo
        echo '```'
      fi
    fi
  done < "$tmp/index"

  cat <<'EOF'

## Embedded in the SQLite wrapper

`github.com/ncruces/go-sqlite3` (MIT, above) runs SQLite as WebAssembly translated to Go by `github.com/ncruces/go-sqlite3-wasm/v6` (MIT-0 for the translation itself; the original authors keep copyright in the translated code, per that module's README). No C compiler is used. The translated code includes:

- **SQLite**, including the FTS5 full-text extension: dedicated to the public domain by its authors (https://sqlite.org/copyright.html). No license text is shipped in the module files.
- **vec1**, the SQLite project's vector search extension (https://sqlite.org/vec1), compiled from the SQLite source tree at the tag named in the wasm module's `vec1/build/build.sh`. **UNVERIFIED:** the module files do not state vec1's license; it is part of the SQLite project's source tree, which publishes itself as public domain, but this was not confirmed from a file shipped in the module.
- **sqlite-parser**, a SQL parser by Marco Bambini, MIT licensed; the text below is the module's `parser/LICENSE`.

EOF
  echo '```text'
  if [ -n "$wasm_dir" ] && [ -f "$wasm_dir/parser/LICENSE" ]; then
    cat "$wasm_dir/parser/LICENSE"
    [ -z "$(tail -c1 "$wasm_dir/parser/LICENSE")" ] || echo
  else
    echo "UNKNOWN: parser/LICENSE not found in the module"
    unknown+=("sqlite-parser (parser/LICENSE missing)")
  fi
  echo '```'
} > "$OUT"

if [ "${#unknown[@]}" -gt 0 ]; then
  echo "gen-notices: UNKNOWN licenses:" >&2
  printf '  %s\n' "${unknown[@]}" >&2
fi
echo "gen-notices: wrote $OUT"
